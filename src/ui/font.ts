export function textWidth(text: string, scale: number): number {
  return text.length * 6 * scale - scale;
}

export function drawText(ctx: CanvasRenderingContext2D, text: string,
                         x: number, y: number, color: string, scale = 2,
                         shadow?: string): void {
  let cx = x;
  for (const raw of text.toUpperCase()) {
    const ch = raw === "*" ? "X2" : raw;
    const glyph = FONT[ch] || FONT["?"];
    for (let gy = 0; gy < 7; gy++) {
      for (let gx = 0; gx < 5; gx++) {
        if (glyph[gy][gx] === "#") {
          if (shadow) {
            ctx.fillStyle = shadow;
            ctx.fillRect(cx + gx * scale + scale, y + gy * scale + scale, scale, scale);
          }
        }
      }
    }
    cx += 6 * scale;
  }
  cx = x;
  for (const raw of text.toUpperCase()) {
    const ch = raw === "*" ? "X2" : raw;
    const glyph = FONT[ch] || FONT["?"];
    for (let gy = 0; gy < 7; gy++) {
      for (let gx = 0; gx < 5; gx++) {
        if (glyph[gy][gx] === "#") {
          ctx.fillStyle = color;
          ctx.fillRect(cx + gx * scale, y + gy * scale, scale, scale);
        }
      }
    }
    cx += 6 * scale;
  }
}

export function makeTextCanvas(text: string, color: string, scale = 2,
                               shadow?: string): HTMLCanvasElement {
  const cv = document.createElement("canvas");
  cv.className = "pixtext";
  cv.width = textWidth(text, scale) + scale * 2;
  cv.height = 9 * scale;
  const ctx = cv.getContext("2d")!;
  drawText(ctx, text, 0, 0, color, scale, shadow);
  return cv;
}
